-- V1 — 1차 ERDCloud 스키마(erdcloud_export_20260907.sql) + 보정
-- PostgreSQL 16 · Flyway V1__init.sql 로 그대로 사용
--
-- 1차의 테이블·컬럼 이름은 그대로 둔다. 바꾼 것은 「지금 프론트·API 가 깨지는 곳」과 무결성 제약만이다.
--   [1] users.onboarding_status 추가 · updated_at 추가          — ProtectedRoute 가 onboarded 로 분기, GET /users/me 가 돌려준다
--   [2] users.nickname NULL 허용                                 — OAuth 직후에는 닉네임이 없다. 온보딩 0단계에서 입력
--   [3] user_actions.book_id NULL 허용 + recommendation_id · rank · occurred_at · client_event_id
--                                                               — IMPRESSION 은 recommendationId 만 보낸다. 추천 CTR 을 재려면 필요
--   [4] recommendations.mode · fallback · based_on_count · weights — 프론트가 fallback 문구·basedOnCount 를 그린다
--   [5] recommendation_items.reason_type 추가 · score NUMERIC    — 계약 §4.4. REAL 은 소수 오차
--   [6] UNIQUE · FK · CHECK — export 에 PK 만 있었다
--   그 외: books.created_at/updated_at (재임베딩 대상 판정), gender CHAR(1), 타입 정리
-- 이름 대응(확정 설계 문서 ↔ 1차): library_items↔user_library · user_events↔user_actions · popular_segments↔book_loaned_top20
--   kdc↔category_code · published_year↔pub_year · cover_image_url↔cover_url · applied_tags↔input_tags · model_version↔feature_version · is_seed↔source
-- 생성 순서 = FK 방향: tags → users → user_interests → books → book_tags → book_loaned_top20 → user_library → recommendations → recommendation_items → user_actions

CREATE TABLE tags (
    tag_code VARCHAR(30) NOT NULL,
    label    VARCHAR(50) NOT NULL,
    kind     VARCHAR(10) NOT NULL,
    PRIMARY KEY (tag_code),
    CONSTRAINT uq_tags_label UNIQUE (label)
);

CREATE TABLE users (
    id                BIGINT       GENERATED BY DEFAULT AS IDENTITY,
    oauth_provider    VARCHAR(20)  NOT NULL,
    oauth_subject     VARCHAR(255) NOT NULL,
    nickname          VARCHAR(50),
    -- [2] OAuth 직후 NULL. 온보딩 0단계(POST /users/me/profile)에서 채운다.
    birth_year        SMALLINT,
    gender            CHAR(1),
    -- 'F' / 'M' / NULL(응답 안 함). 1차 VARCHAR(10) → CHAR(1)
    onboarding_status VARCHAR(10)  NOT NULL DEFAULT 'PENDING',
    -- [1] PENDING / COMPLETED / SKIPPED. 프론트 onboarded = (status <> 'PENDING')
    created_at        TIMESTAMPTZ  NOT NULL DEFAULT now(),
    updated_at        TIMESTAMPTZ  NOT NULL DEFAULT now(),
    PRIMARY KEY (id),
    CONSTRAINT uq_users_oauth UNIQUE (oauth_provider, oauth_subject),
    CONSTRAINT ck_users_provider CHECK (oauth_provider IN ('KAKAO','GOOGLE')),
    CONSTRAINT ck_users_gender CHECK (gender IS NULL OR gender IN ('F','M')),
    CONSTRAINT ck_users_onboarding CHECK (onboarding_status IN ('PENDING','COMPLETED','SKIPPED')),
    CONSTRAINT ck_users_birth_year CHECK (birth_year IS NULL OR birth_year BETWEEN 1900 AND 2100)
);

CREATE TABLE user_interests (
    id         BIGINT      GENERATED BY DEFAULT AS IDENTITY,
    user_id    BIGINT      NOT NULL,
    tag_code   VARCHAR(30) NOT NULL,
    created_at TIMESTAMPTZ NOT NULL DEFAULT now(),
    PRIMARY KEY (id),
    CONSTRAINT uq_ui_user_tag UNIQUE (user_id, tag_code),
    CONSTRAINT fk_ui_user FOREIGN KEY (user_id) REFERENCES users (id) ON DELETE CASCADE,
    CONSTRAINT fk_ui_tag  FOREIGN KEY (tag_code) REFERENCES tags (tag_code)
);

CREATE TABLE books (
    id                BIGINT       GENERATED BY DEFAULT AS IDENTITY,
    isbn13            CHAR(13)     NOT NULL,
    title             VARCHAR(500) NOT NULL,
    author            VARCHAR(300),
    publisher         VARCHAR(200),
    pub_year          SMALLINT,
    category_code     VARCHAR(10),
    -- KDC. 원장 1,660개관 최빈값 (1단계 100%)
    description       TEXT,
    cover_url         VARCHAR(500),
    embedding_version VARCHAR(30),
    -- V2 에서 book_embeddings 로 옮긴다. 지금은 그대로.
    created_at        TIMESTAMPTZ  NOT NULL DEFAULT now(),
    updated_at        TIMESTAMPTZ  NOT NULL DEFAULT now(),
    PRIMARY KEY (id),
    CONSTRAINT uq_books_isbn13 UNIQUE (isbn13),
    CONSTRAINT ck_books_isbn13 CHECK (isbn13 ~ '^(978|979)[0-9]{10}$'),
    CONSTRAINT ck_books_pub_year CHECK (pub_year IS NULL OR pub_year BETWEEN 1000 AND 2100)
);
CREATE INDEX idx_books_category ON books (category_code);
CREATE INDEX idx_books_pub_year ON books (pub_year);

CREATE TABLE book_tags (
    id       BIGINT      GENERATED BY DEFAULT AS IDENTITY,
    book_id  BIGINT      NOT NULL,
    tag_code VARCHAR(30) NOT NULL,
    PRIMARY KEY (id),
    CONSTRAINT uq_bt_book_tag UNIQUE (book_id, tag_code),
    CONSTRAINT fk_bt_book FOREIGN KEY (book_id) REFERENCES books (id) ON DELETE CASCADE,
    CONSTRAINT fk_bt_tag  FOREIGN KEY (tag_code) REFERENCES tags (tag_code)
);
CREATE INDEX idx_bt_tag ON book_tags (tag_code);

CREATE TABLE book_loaned_top20 (
    id         BIGINT   GENERATED BY DEFAULT AS IDENTITY,
    book_id    BIGINT   NOT NULL,
    gender     CHAR(1)  NOT NULL,
    age_group  VARCHAR(2) NOT NULL,
    -- '10' '20' … '50' (50+ 는 '50')
    ranking    SMALLINT NOT NULL,
    loan_count INTEGER,
    period     CHAR(6)  NOT NULL,
    -- 'YYYYMM' 기준월
    PRIMARY KEY (id),
    CONSTRAINT uq_blt_slot UNIQUE (period, gender, age_group, ranking),
    CONSTRAINT ck_blt_gender CHECK (gender IN ('F','M')),
    CONSTRAINT ck_blt_ranking CHECK (ranking >= 1),
    CONSTRAINT ck_blt_period CHECK (period ~ '^[0-9]{6}$'),
    CONSTRAINT fk_blt_book FOREIGN KEY (book_id) REFERENCES books (id) ON DELETE CASCADE
);
CREATE INDEX idx_blt_book ON book_loaned_top20 (book_id);

CREATE TABLE user_library (
    id          BIGINT       GENERATED BY DEFAULT AS IDENTITY,
    user_id     BIGINT       NOT NULL,
    book_id     BIGINT       NOT NULL,
    status      VARCHAR(15)  NOT NULL,
    rating      SMALLINT,
    review_text VARCHAR(300),
    finished_at DATE,
    source      VARCHAR(15)  NOT NULL DEFAULT 'SERVICE',
    -- SERVICE / ONBOARDING. 온보딩에서 고른 책(seed)을 이후 기록과 구분
    created_at  TIMESTAMPTZ  NOT NULL DEFAULT now(),
    updated_at  TIMESTAMPTZ  NOT NULL DEFAULT now(),
    PRIMARY KEY (id),
    CONSTRAINT uq_ul_user_book UNIQUE (user_id, book_id),
    CONSTRAINT ck_ul_status CHECK (status IN ('WISH','READING','READ')),
    CONSTRAINT ck_ul_rating CHECK (rating IS NULL OR rating BETWEEN 1 AND 5),
    CONSTRAINT ck_ul_review CHECK (review_text IS NULL OR btrim(review_text) <> ''),
    CONSTRAINT ck_ul_source CHECK (source IN ('SERVICE','ONBOARDING')),
    CONSTRAINT ck_ul_finished CHECK (
        (status = 'READ' AND finished_at IS NOT NULL) OR
        (status <> 'READ' AND finished_at IS NULL)),
    CONSTRAINT fk_ul_user FOREIGN KEY (user_id) REFERENCES users (id) ON DELETE CASCADE,
    CONSTRAINT fk_ul_book FOREIGN KEY (book_id) REFERENCES books (id)
);
CREATE INDEX idx_ul_user_status ON user_library (user_id, status, updated_at DESC);
CREATE INDEX idx_ul_user_read   ON user_library (user_id, finished_at DESC) WHERE status = 'READ';

CREATE TABLE recommendations (
    id              BIGINT      GENERATED BY DEFAULT AS IDENTITY,
    user_id         BIGINT      NOT NULL,
    mode            VARCHAR(15) NOT NULL DEFAULT 'COLD_START',
    -- [4] COLD_START / PERSONALIZED
    fallback        BOOLEAN     NOT NULL DEFAULT FALSE,
    -- [4] true = 개인화 실패로 세그먼트 인기 대체. 프론트 문구 분기
    based_on_count  SMALLINT    NOT NULL DEFAULT 0,
    -- [4] "최근 기록한 N권을 보고 골랐어요"
    weights         JSONB       NOT NULL DEFAULT '{}'::jsonb,
    -- [4] { taste, coLoan, trending, steady, newField }
    input_tags      JSONB       NOT NULL DEFAULT '[]'::jsonb,
    -- API 의 appliedTags. tags.tag_code 배열
    feature_version VARCHAR(30),
    -- API 의 modelVersion
    created_at      TIMESTAMPTZ NOT NULL DEFAULT now(),
    -- API 의 generatedAt
    PRIMARY KEY (id),
    CONSTRAINT ck_rec_mode CHECK (mode IN ('COLD_START','PERSONALIZED')),
    CONSTRAINT ck_rec_weights CHECK (jsonb_typeof(weights) = 'object'),
    CONSTRAINT ck_rec_tags CHECK (jsonb_typeof(input_tags) = 'array'),
    CONSTRAINT fk_rec_user FOREIGN KEY (user_id) REFERENCES users (id) ON DELETE CASCADE
);
CREATE INDEX idx_rec_user_created ON recommendations (user_id, created_at DESC);

CREATE TABLE recommendation_items (
    id                BIGINT       GENERATED BY DEFAULT AS IDENTITY,
    recommendation_id BIGINT       NOT NULL,
    book_id           BIGINT       NOT NULL,
    rank              SMALLINT     NOT NULL,
    score             NUMERIC(5,2) NOT NULL,
    -- [5] REAL → NUMERIC(5,2), 0~100
    tags              JSONB        NOT NULL DEFAULT '[]'::jsonb,
    feature_scores    JSONB        NOT NULL DEFAULT '{}'::jsonb,
    reason_type       VARCHAR(20)  NOT NULL,
    -- [5] 계약 §4.4
    reason_text       TEXT         NOT NULL,
    -- 카드에 항상 표시 — MVP 완료 조건
    PRIMARY KEY (id),
    CONSTRAINT uq_ri_rec_book UNIQUE (recommendation_id, book_id),
    CONSTRAINT uq_ri_rec_rank UNIQUE (recommendation_id, rank),
    CONSTRAINT ck_ri_rank CHECK (rank >= 1),
    CONSTRAINT ck_ri_score CHECK (score BETWEEN 0 AND 100),
    CONSTRAINT ck_ri_reason CHECK (reason_type IN
        ('SAME_AUTHOR','SAME_CATEGORY','TEXT_SIMILARITY','SEGMENT_POPULAR',
         'DEMAND_POPULAR','MOMENTUM','NEW_BOOK','INITIAL_PREFERENCE')),
    CONSTRAINT fk_ri_rec  FOREIGN KEY (recommendation_id) REFERENCES recommendations (id) ON DELETE CASCADE,
    CONSTRAINT fk_ri_book FOREIGN KEY (book_id) REFERENCES books (id)
);

CREATE TABLE user_actions (
    id                BIGINT      GENERATED BY DEFAULT AS IDENTITY,
    user_id           BIGINT      NOT NULL,
    book_id           BIGINT,
    -- [3] NULL 허용. IMPRESSION 은 덱 단위(recommendationId 만)
    recommendation_id BIGINT,
    -- [3] 추천 CTR 계산 키
    event_type        VARCHAR(15) NOT NULL,
    rank              SMALLINT,
    -- [3] 노출 당시 순위
    context           VARCHAR(20),
    -- 1차 그대로. RECOMMEND / HOME / SEARCH / DETAIL 등 화면 출처
    client_event_id   VARCHAR(64),
    -- [3] 재전송 중복 방지
    occurred_at       TIMESTAMPTZ NOT NULL DEFAULT now(),
    -- [3] 클라이언트 발생 시각. created_at 은 서버 수신
    created_at        TIMESTAMPTZ NOT NULL DEFAULT now(),
    PRIMARY KEY (id),
    CONSTRAINT uq_ua_client UNIQUE (user_id, client_event_id),
    CONSTRAINT ck_ua_type CHECK (event_type IN ('IMPRESSION','CLICK','REASON_VIEW','BOOK_VIEW','WISH')),
    CONSTRAINT fk_ua_user FOREIGN KEY (user_id) REFERENCES users (id) ON DELETE CASCADE,
    CONSTRAINT fk_ua_book FOREIGN KEY (book_id) REFERENCES books (id),
    CONSTRAINT fk_ua_rec  FOREIGN KEY (recommendation_id) REFERENCES recommendations (id)
);
CREATE INDEX idx_ua_occurred  ON user_actions (occurred_at);
CREATE INDEX idx_ua_rec_type  ON user_actions (recommendation_id, event_type) WHERE recommendation_id IS NOT NULL;
CREATE INDEX idx_ua_user_book ON user_actions (user_id, book_id, occurred_at DESC) WHERE book_id IS NOT NULL;
