-- V12 — 리프레시 토큰 (2026-09-22). 액세스 JWT 를 15분으로 줄이면서 로그인이 끊기지 않게, 갱신 자격을 서버가 보관한다 (API_SPEC §2.3·§2.4).
--
-- 왜
--   [1] JWT 만 있던 설계는 만료가 곧 로그아웃이다. 운영 TTL 을 24시간 → 15분으로 내린 뒤로는 15분마다 튕긴다.
--   [2] 무상태 JWT 는 서버가 끊을 방법이 없다. 로그아웃·계정 이상 시 세션을 폐기할 자리가 필요하다.
--   [3] 정석(RFC 9700 · OAuth for Browser-Based Apps): 액세스 토큰은 짧게·메모리에, 리프레시 토큰은 HttpOnly 쿠키에, 쓸 때마다 회전하고 재사용을 감지한다.
--
-- token_hash  : 브라우저에 준 32바이트 난수(base64url)의 sha256 hex. 평문은 저장하지 않는다 — DB 가 유출돼도 토큰을 복원할 수 없다.
-- family_id   : 로그인 한 번 = 계열 하나. 회전할 때마다 같은 계열로 새 행을 만든다. 옛 토큰이 다시 쓰이면(재사용) 계열 전체를 폐기한다.
-- expires_at  : 절대 만료. 회전해도 계열이 만들어진 시각 + app.jwt.refresh-ttl-seconds(기본 14일)을 넘기지 않는다.
-- rotated_at  : 이 행이 후속 행으로 교체된 시각. NULL 이면 현재 유효한 토큰. 교체 뒤 유예(app.jwt.refresh-grace-seconds, 기본 10초) 안의 재사용은
--               탭 두 개가 동시에 갱신한 경합으로 보고 액세스 토큰만 다시 내준다. 유예 밖이면 도용으로 본다.
-- revoked_at  : 로그아웃 또는 재사용 감지로 폐기된 시각.
-- 정리        : RefreshTokenPurgeJob 이 매일 만료·폐기·교체 뒤 하루 지난 행을 지운다. 교체 행은 재사용 감지를 위해 하루는 남긴다.

CREATE TABLE refresh_tokens (
    id          BIGINT       GENERATED BY DEFAULT AS IDENTITY,
    user_id     BIGINT       NOT NULL,
    family_id   UUID         NOT NULL,
    token_hash  CHAR(64)     NOT NULL,
    issued_at   TIMESTAMPTZ  NOT NULL DEFAULT now(),
    expires_at  TIMESTAMPTZ  NOT NULL,
    rotated_at  TIMESTAMPTZ,
    revoked_at  TIMESTAMPTZ,
    PRIMARY KEY (id),
    CONSTRAINT uq_rt_token_hash UNIQUE (token_hash),
    CONSTRAINT fk_rt_user FOREIGN KEY (user_id) REFERENCES users (id) ON DELETE CASCADE
);

CREATE INDEX idx_rt_family ON refresh_tokens (family_id);
CREATE INDEX idx_rt_user   ON refresh_tokens (user_id);
CREATE INDEX idx_rt_expires ON refresh_tokens (expires_at);
