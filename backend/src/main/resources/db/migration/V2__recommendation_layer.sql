-- V2 — 추천 데이터 층 (2026-09-09). V1(1차 ERDCloud 10테이블 + 보정) 위에 올린다. 이름은 1차 규칙(books.id BIGINT · category_code 등)을 따른다.
--
-- 무엇이 들어오나 (원천: 정보나루 usageAnalysisList 스냅샷 · 원장 · 카카오)
--   books 확장          description_source(정보나루/카카오/형제 권) · description_kakao(두 번째 소개문) · text_hash(임베딩 입력 해시)
--                       ∵ 설계 문서의 book_texts 표를 컬럼 3개로 흡수 — 소스가 둘뿐이고 임베딩 입력이 둘을 다 쓰는 것만이 필요했다 (09-09 결정)
--   kdc_codes           KDC 코드 → 이름·상위. 정보나루 class_nm 「대 > 중 > 소」에서 파생 (3자리 849개, 라벨 일관성 99.9%)
--   book_keywords       정보나루 키워드 50개·가중치 (1단계 48% · L1 17%). 어휘 색인이 50개 다 쓴다, 밀집 입력은 상위 30
--   book_relations      함께대출·마니아·다독자 (1단계 83%) — 주 추천 신호. target 이 카탈로그에 없으면 target_book_id NULL, ISBN 은 보존
--   book_demand_features 월 단위 수요 지표. 지금 채울 수 있는 것: 누적(원장) · 최근 3/12개월(정보나루 loan_history) · 소장관 수. trending/steady 는 다음 스냅샷부터
--   book_embeddings     책당 벡터 1개(e5-large 1024d, fp16 BYTEA). 이 마이그레이션은 표만 만든다. ES 가 탐색, PG 는 정본
-- 넣지 않는 것: book_texts(컬럼으로 흡수) · book_demographics(3.2%) · 도서관 원장(MVP 배제)
-- 생성 순서 = FK 방향: books 확장 → kdc_codes → book_keywords → book_relations → book_demand_features → book_embeddings

ALTER TABLE books
    ADD COLUMN description_source VARCHAR(20),
    ADD COLUMN description_kakao  TEXT,
    ADD COLUMN text_hash          CHAR(64);
-- description_source: DATA4LIBRARY / KAKAO / SIBLING(같은 세트 형제 권의 소개) / NULL(없음)
-- description_kakao : 카카오 소개 원문. 대표(description)가 카카오면 NULL — 같은 글을 두 번 넣지 않는다
-- text_hash         : STRUCT 임베딩 입력(제목/저자/분류/키워드 30/소개 둘) 의 SHA-256. 바뀐 책만 재임베딩
ALTER TABLE books ADD CONSTRAINT ck_books_desc_source
    CHECK (description_source IS NULL OR description_source IN ('DATA4LIBRARY','KAKAO','SIBLING'));

CREATE TABLE kdc_codes (
    code        VARCHAR(10)  NOT NULL,
    -- '8' · '81' · '813' 세 단계. books.category_code 는 '813.62' 처럼 소수점까지라 left(category_code, n) 으로 조인한다
    label       VARCHAR(200) NOT NULL,
    parent_code VARCHAR(10),
    depth       SMALLINT     NOT NULL,
    -- 1 대분류(10) · 2 중분류 · 3 소분류
    PRIMARY KEY (code),
    CONSTRAINT ck_kdc_depth CHECK (depth BETWEEN 1 AND 3),
    CONSTRAINT fk_kdc_parent FOREIGN KEY (parent_code) REFERENCES kdc_codes (code)
);

CREATE TABLE book_keywords (
    book_id BIGINT       NOT NULL,
    keyword VARCHAR(100) NOT NULL,
    weight  NUMERIC(8,2),
    rank    SMALLINT     NOT NULL,
    -- API 가 준 순서(가중치 내림차순 99.4%). 1위 16.4 → 10위 3.9 → 50위 1.7
    PRIMARY KEY (book_id, keyword),
    CONSTRAINT fk_bk_book FOREIGN KEY (book_id) REFERENCES books (id) ON DELETE CASCADE
);
CREATE INDEX idx_bk_keyword ON book_keywords (keyword);
-- ∵ 어휘 후보 생성: 같은 키워드를 가진 책 조인. TF-IDF 가 밀집을 이긴 이유의 절반이 키워드 정확 겹침이다

CREATE TABLE book_relations (
    id             BIGINT      GENERATED BY DEFAULT AS IDENTITY,
    source_book_id BIGINT      NOT NULL,
    target_book_id BIGINT,
    -- NULL = 대상이 카탈로그(books)에 없음. 함께대출 정답의 3~17% 가 그렇다. 적재될 때 연결한다
    target_isbn13  CHAR(13)    NOT NULL,
    relation_type  VARCHAR(12) NOT NULL,
    -- CO_LOAN(함께대출 — 인기 편향, 상위 1% 책 25.7%) · MANIA_REC(마니아 — 취향 신호, 3.9%) · READER_REC(다독자)
    rank           SMALLINT    NOT NULL,
    collected_at   DATE        NOT NULL,
    PRIMARY KEY (id),
    CONSTRAINT uq_br UNIQUE (source_book_id, relation_type, target_isbn13),
    CONSTRAINT ck_br_type CHECK (relation_type IN ('CO_LOAN','MANIA_REC','READER_REC')),
    CONSTRAINT ck_br_rank CHECK (rank >= 1),
    CONSTRAINT fk_br_src FOREIGN KEY (source_book_id) REFERENCES books (id) ON DELETE CASCADE,
    CONSTRAINT fk_br_tgt FOREIGN KEY (target_book_id) REFERENCES books (id)
);
CREATE INDEX idx_br_src_type  ON book_relations (source_book_id, relation_type, rank);
CREATE INDEX idx_br_unlinked  ON book_relations (target_isbn13) WHERE target_book_id IS NULL;
-- 방향이 있다(대칭 30%). (source → target) 그대로 두고 역방향을 만들지 않는다

CREATE TABLE book_demand_features (
    book_id         BIGINT      NOT NULL,
    as_of_month     CHAR(7)     NOT NULL,
    -- 'YYYY-MM' 스냅샷 기준월. PK 에 넣는다 — 덮어쓰면 차분·모멘텀(결정 3)을 못 만든다
    loan_cum        BIGINT,
    -- 원장 누적 대출 합. 필터·prior 전용, 랭킹 주신호 금지
    loan_3m         INTEGER,
    loan_12m        INTEGER,
    -- 정보나루 loan_history(최근 12개월) 합. 없는 책(15%)은 NULL — 0(대출 없음) 과 다르다
    loan_24m        INTEGER,
    trending_score  NUMERIC(5,2),
    steady_score    NUMERIC(5,2),
    -- NULL = 아직 계산 불가(스냅샷 1개). 다음 달 원장부터 채운다
    holder_libs     INTEGER,
    feature_version VARCHAR(20) NOT NULL,
    PRIMARY KEY (book_id, as_of_month),
    CONSTRAINT fk_bdf_book FOREIGN KEY (book_id) REFERENCES books (id) ON DELETE CASCADE
);
CREATE INDEX idx_bdf_month_3m  ON book_demand_features (as_of_month, loan_3m DESC NULLS LAST);
CREATE INDEX idx_bdf_month_cum ON book_demand_features (as_of_month, loan_cum DESC NULLS LAST);

CREATE TABLE book_embeddings (
    book_id     BIGINT      NOT NULL,
    model       VARCHAR(50) NOT NULL,
    -- 'multilingual-e5-large'
    dim         SMALLINT    NOT NULL,
    vector_fp16 BYTEA       NOT NULL,
    -- dim × 2 바이트. 유사도 탐색은 Elasticsearch dense_vector(int8_hnsw) 가 하고 여기는 정본
    input_hash  CHAR(64)    NOT NULL,
    -- books.text_hash 와 같으면 최신. 다르면 재임베딩 대상
    built_at    TIMESTAMPTZ NOT NULL DEFAULT now(),
    PRIMARY KEY (book_id, model),
    CONSTRAINT fk_be_book FOREIGN KEY (book_id) REFERENCES books (id) ON DELETE CASCADE
);
