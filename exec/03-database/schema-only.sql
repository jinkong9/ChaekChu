CREATE TABLE tags (
    tag_code VARCHAR(30) NOT NULL,
    label    VARCHAR(50) NOT NULL,
    kind     VARCHAR(10) NOT NULL,
    PRIMARY KEY (tag_code),
    CONSTRAINT uq_tags_label UNIQUE (label)
);

CREATE TABLE users (
    id                BIGINT       GENERATED BY DEFAULT AS IDENTITY,
    oauth_provider    VARCHAR(20)  NOT NULL,
    oauth_subject     VARCHAR(255) NOT NULL,
    nickname          VARCHAR(50),
    -- [2] OAuth 직후 NULL. 온보딩 0단계(POST /users/me/profile)에서 채운다.
    birth_year        SMALLINT,
    gender            CHAR(1),
    -- 'F' / 'M' / NULL(응답 안 함). 1차 VARCHAR(10) → CHAR(1)
    onboarding_status VARCHAR(10)  NOT NULL DEFAULT 'PENDING',
    -- [1] PENDING / COMPLETED / SKIPPED. 프론트 onboarded = (status <> 'PENDING')
    created_at        TIMESTAMPTZ  NOT NULL DEFAULT now(),
    updated_at        TIMESTAMPTZ  NOT NULL DEFAULT now(),
    PRIMARY KEY (id),
    CONSTRAINT uq_users_oauth UNIQUE (oauth_provider, oauth_subject),
    CONSTRAINT ck_users_provider CHECK (oauth_provider IN ('KAKAO','GOOGLE')),
    CONSTRAINT ck_users_gender CHECK (gender IS NULL OR gender IN ('F','M')),
    CONSTRAINT ck_users_onboarding CHECK (onboarding_status IN ('PENDING','COMPLETED','SKIPPED')),
    CONSTRAINT ck_users_birth_year CHECK (birth_year IS NULL OR birth_year BETWEEN 1900 AND 2100)
);

CREATE TABLE user_interests (
    id         BIGINT      GENERATED BY DEFAULT AS IDENTITY,
    user_id    BIGINT      NOT NULL,
    tag_code   VARCHAR(30) NOT NULL,
    created_at TIMESTAMPTZ NOT NULL DEFAULT now(),
    PRIMARY KEY (id),
    CONSTRAINT uq_ui_user_tag UNIQUE (user_id, tag_code),
    CONSTRAINT fk_ui_user FOREIGN KEY (user_id) REFERENCES users (id) ON DELETE CASCADE,
    CONSTRAINT fk_ui_tag  FOREIGN KEY (tag_code) REFERENCES tags (tag_code)
);

CREATE TABLE books (
    id                BIGINT       GENERATED BY DEFAULT AS IDENTITY,
    isbn13            CHAR(13)     NOT NULL,
    title             VARCHAR(500) NOT NULL,
    author            VARCHAR(300),
    publisher         VARCHAR(200),
    pub_year          SMALLINT,
    category_code     VARCHAR(10),
    -- KDC. 원장 1,660개관 최빈값 (1단계 100%)
    description       TEXT,
    cover_url         VARCHAR(500),
    embedding_version VARCHAR(30),
    -- V2 에서 book_embeddings 로 옮긴다. 지금은 그대로.
    created_at        TIMESTAMPTZ  NOT NULL DEFAULT now(),
    updated_at        TIMESTAMPTZ  NOT NULL DEFAULT now(),
    PRIMARY KEY (id),
    CONSTRAINT uq_books_isbn13 UNIQUE (isbn13),
    CONSTRAINT ck_books_isbn13 CHECK (isbn13 ~ '^(978|979)[0-9]{10}$'),
    CONSTRAINT ck_books_pub_year CHECK (pub_year IS NULL OR pub_year BETWEEN 1000 AND 2100)
);
CREATE INDEX idx_books_category ON books (category_code);
CREATE INDEX idx_books_pub_year ON books (pub_year);

CREATE TABLE book_tags (
    id       BIGINT      GENERATED BY DEFAULT AS IDENTITY,
    book_id  BIGINT      NOT NULL,
    tag_code VARCHAR(30) NOT NULL,
    PRIMARY KEY (id),
    CONSTRAINT uq_bt_book_tag UNIQUE (book_id, tag_code),
    CONSTRAINT fk_bt_book FOREIGN KEY (book_id) REFERENCES books (id) ON DELETE CASCADE,
    CONSTRAINT fk_bt_tag  FOREIGN KEY (tag_code) REFERENCES tags (tag_code)
