CREATE TABLE book_loaned_top20 (
    id         BIGINT   GENERATED BY DEFAULT AS IDENTITY,
    book_id    BIGINT   NOT NULL,
    gender     CHAR(1)  NOT NULL,
    age_group  VARCHAR(2) NOT NULL,
    -- '10' '20' … '50' (50+ 는 '50')
    ranking    SMALLINT NOT NULL,
    loan_count INTEGER,
    period     CHAR(6)  NOT NULL,
    -- 'YYYYMM' 기준월
    PRIMARY KEY (id),
    CONSTRAINT uq_blt_slot UNIQUE (period, gender, age_group, ranking),
    CONSTRAINT ck_blt_gender CHECK (gender IN ('F','M')),
    CONSTRAINT ck_blt_ranking CHECK (ranking >= 1),
    CONSTRAINT ck_blt_period CHECK (period ~ '^[0-9]{6}$'),
    CONSTRAINT fk_blt_book FOREIGN KEY (book_id) REFERENCES books (id) ON DELETE CASCADE
);
CREATE INDEX idx_blt_book ON book_loaned_top20 (book_id);

CREATE TABLE user_library (
    id          BIGINT       GENERATED BY DEFAULT AS IDENTITY,
    user_id     BIGINT       NOT NULL,
    book_id     BIGINT       NOT NULL,
    status      VARCHAR(15)  NOT NULL,
    -- [7] WISH / READ. 09-02 2단 확정 — READING 없음. 찜 = WISH
    rating      SMALLINT,
    review_text VARCHAR(300),
    finished_at DATE,
    -- [7] READ 일 때만. 서재 API(POST/PATCH /library)로 READ 가 되면 서버가 오늘로 채운다.
    --     온보딩 seed(POST /users/me/preferences)는 READ 인데 NULL — 서비스 이전에 읽은 책. 프론트가 연표·통계에서 뺀다.
    source      VARCHAR(15)  NOT NULL DEFAULT 'SERVICE',
    -- SERVICE / ONBOARDING. 온보딩에서 고른 책(seed)을 이후 기록과 구분
    created_at  TIMESTAMPTZ  NOT NULL DEFAULT now(),
    updated_at  TIMESTAMPTZ  NOT NULL DEFAULT now(),
    PRIMARY KEY (id),
    CONSTRAINT uq_ul_user_book UNIQUE (user_id, book_id),
    CONSTRAINT ck_ul_status CHECK (status IN ('WISH','READ')),
    CONSTRAINT ck_ul_rating CHECK (rating IS NULL OR rating BETWEEN 1 AND 5),
    CONSTRAINT ck_ul_review CHECK (review_text IS NULL OR btrim(review_text) <> ''),
    CONSTRAINT ck_ul_source CHECK (source IN ('SERVICE','ONBOARDING')),
    CONSTRAINT ck_ul_finished CHECK (status = 'READ' OR finished_at IS NULL),
    -- [7] WISH 면 완독일 없음. READ 는 있어도(서재 API) 없어도(온보딩 seed) 된다
    CONSTRAINT fk_ul_user FOREIGN KEY (user_id) REFERENCES users (id) ON DELETE CASCADE,
    CONSTRAINT fk_ul_book FOREIGN KEY (book_id) REFERENCES books (id)
);
CREATE INDEX idx_ul_user_status ON user_library (user_id, status, updated_at DESC);
CREATE INDEX idx_ul_user_read   ON user_library (user_id, finished_at DESC) WHERE status = 'READ';

CREATE TABLE recommendations (
    id              BIGINT      GENERATED BY DEFAULT AS IDENTITY,
    user_id         BIGINT      NOT NULL,
    mode            VARCHAR(15) NOT NULL DEFAULT 'COLD_START',
    -- [4] COLD_START / PERSONALIZED
    fallback        BOOLEAN     NOT NULL DEFAULT FALSE,
    -- [4] true = 개인화 실패로 세그먼트 인기 대체. 프론트 문구 분기
    based_on_count  SMALLINT    NOT NULL DEFAULT 0,
    -- [4] "최근 기록한 N권을 보고 골랐어요"
    weights         JSONB       NOT NULL DEFAULT '{}'::jsonb,
    -- [4] { taste, coLoan, trending, steady, newField }
    input_tags      JSONB       NOT NULL DEFAULT '[]'::jsonb,
    -- API 의 appliedTags. tags.tag_code 배열
    feature_version VARCHAR(30),
    -- API 의 modelVersion
    created_at      TIMESTAMPTZ NOT NULL DEFAULT now(),
    -- API 의 generatedAt
    PRIMARY KEY (id),
    CONSTRAINT ck_rec_mode CHECK (mode IN ('COLD_START','PERSONALIZED')),
    CONSTRAINT ck_rec_weights CHECK (jsonb_typeof(weights) = 'object'),
    CONSTRAINT ck_rec_tags CHECK (jsonb_typeof(input_tags) = 'array'),
    CONSTRAINT fk_rec_user FOREIGN KEY (user_id) REFERENCES users (id) ON DELETE CASCADE
);
CREATE INDEX idx_rec_user_created ON recommendations (user_id, created_at DESC);

CREATE TABLE recommendation_items (
    id                BIGINT       GENERATED BY DEFAULT AS IDENTITY,
    recommendation_id BIGINT       NOT NULL,
    book_id           BIGINT       NOT NULL,
    rank              SMALLINT     NOT NULL,
    score             NUMERIC(5,2) NOT NULL,
    -- [5] REAL → NUMERIC(5,2), 0~100
    tags              JSONB        NOT NULL DEFAULT '[]'::jsonb,
    feature_scores    JSONB        NOT NULL DEFAULT '{}'::jsonb,
    reason_type       VARCHAR(20)  NOT NULL,
    -- [5] 계약 §4.4
    reason_text       TEXT         NOT NULL,
    -- 카드에 항상 표시 — MVP 완료 조건
    PRIMARY KEY (id),
    CONSTRAINT uq_ri_rec_book UNIQUE (recommendation_id, book_id),
    CONSTRAINT uq_ri_rec_rank UNIQUE (recommendation_id, rank),
    CONSTRAINT ck_ri_rank CHECK (rank >= 1),
    CONSTRAINT ck_ri_score CHECK (score BETWEEN 0 AND 100),
    CONSTRAINT ck_ri_reason CHECK (reason_type IN
        ('SAME_AUTHOR','SAME_CATEGORY','TEXT_SIMILARITY','SEGMENT_POPULAR',
         'DEMAND_POPULAR','MOMENTUM','NEW_BOOK','INITIAL_PREFERENCE')),
    CONSTRAINT fk_ri_rec  FOREIGN KEY (recommendation_id) REFERENCES recommendations (id) ON DELETE CASCADE,
    CONSTRAINT fk_ri_book FOREIGN KEY (book_id) REFERENCES books (id)
);

CREATE TABLE user_actions (
    id                BIGINT      GENERATED BY DEFAULT AS IDENTITY,
    user_id           BIGINT      NOT NULL,
    book_id           BIGINT,
    -- [3] NULL 허용. IMPRESSION 은 덱 단위(recommendationId 만)
    recommendation_id BIGINT,
    -- [3] 추천 CTR 계산 키
    event_type        VARCHAR(15) NOT NULL,
    rank              SMALLINT,
    -- [3] 노출 당시 순위
    context           VARCHAR(20),
    -- 1차 그대로. RECOMMEND / HOME / SEARCH / DETAIL 등 화면 출처
    client_event_id   VARCHAR(64),
    -- [3] 재전송 중복 방지
    occurred_at       TIMESTAMPTZ NOT NULL DEFAULT now(),
    -- [3] 클라이언트 발생 시각. created_at 은 서버 수신
    created_at        TIMESTAMPTZ NOT NULL DEFAULT now(),
    PRIMARY KEY (id),
    CONSTRAINT uq_ua_client UNIQUE (user_id, client_event_id),
    CONSTRAINT ck_ua_type CHECK (event_type IN ('IMPRESSION','CLICK','REASON_VIEW','BOOK_VIEW','WISH')),
    CONSTRAINT fk_ua_user FOREIGN KEY (user_id) REFERENCES users (id) ON DELETE CASCADE,
    CONSTRAINT fk_ua_book FOREIGN KEY (book_id) REFERENCES books (id),
    CONSTRAINT fk_ua_rec  FOREIGN KEY (recommendation_id) REFERENCES recommendations (id)
);
CREATE INDEX idx_ua_occurred  ON user_actions (occurred_at);
CREATE INDEX idx_ua_rec_type  ON user_actions (recommendation_id, event_type) WHERE recommendation_id IS NOT NULL;
CREATE INDEX idx_ua_user_book ON user_actions (user_id, book_id, occurred_at DESC) WHERE book_id IS NOT NULL;

